const hostOf = (url) => {
  try {
    return new URL(url.includes('://') ? url : `https://${url}`).hostname
      .toLowerCase()
      .replace(/^www\./, '');
  } catch {
    return '';
  }
};

/**
 * The icon for a URL, or an empty string when the site is not one of the known
 * ones. Subdomains fall back to their parent, so mail.google.com finds gmail.
 */
export const brandIconFor = (url) => {
  const host = hostOf(url);

  if (!host) return '';

  const parts = host.split('.');

  for (let index = 0; index < parts.length - 1; index += 1) {
    const match = ICONS[parts.slice(index).join('.')];

    if (match) {
      const [source, slug] = match.split(':');

      return `${CDN[source]}${slug}.svg`;
    }
  }

  return '';
};

/** True when an icon URL is one of ours, which is what the tile tints. */
export const isBrandIcon = (url) =>
  Boolean(url) && Object.values(CDN).some((base) => url.startsWith(base));
